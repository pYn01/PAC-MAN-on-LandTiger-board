void Draw_table(){

	int i,j;
	for(i=0; i<N_righe; i++){
		for(j=0; j<N_colonne; j++){
			if(Griglia[i][j] == 1){
				LCD_DrawLine(8+j*8, 36+i*8, 16+j*8, 36+i*8, Blue);
				LCD_DrawLine(8+j*8, 36+i*8, 8+j*8, 36+8+i*8, Blue);
				LCD_DrawLine(16+j*8, 36+i*8, 16+j*8, 36+8+i*8, Blue);
				LCD_DrawLine(8+j*8, 36+8+i*8, 16+j*8, 36+8+i*8, Blue);
			}
			if(Griglia[i][j] == 0){
				Pills=Pills+1;
				LCD_SetPoint(8+4+j*8, 36+4+i*8, Green);
				LCD_SetPoint(8+5+j*8, 36+4+i*8, Green);
				LCD_SetPoint(8+4+j*8, 36+5+i*8, Green);
				LCD_SetPoint(8+5+j*8, 36+5+i*8, Green);
			}
		}
	}
}

